"""Generate deterministic 11px outlines from the bundled FontStruct source fonts.

Requires fonttools. Optional --preview also requires Pillow. No browser rendering,
font hinting, antialiasing or kerning participates in the generated glyphs.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.pointInsidePen import PointInsidePen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'ui': ROOT / 'node_modules/98.css/fonts/src/ms-sans-serif/MS Sans Serif.ttf',
    'bold': ROOT / 'node_modules/98.css/fonts/src/ms-sans-serif-bold/MS Sans Serif Bold.ttf',
}
DESTINATION = ROOT / 'src/lib/gfx/bitmap-font.ts'


def generate(path: Path) -> dict[int, dict]:
    font = TTFont(path)
    glyph_set = font.getGlyphSet()
    scale = 11 / font['head'].unitsPerEm
    result = {}
    for codepoint, name in sorted(font.getBestCmap().items()):
        glyph = glyph_set[name]
        bounds = BoundsPen(glyph_set)
        glyph.draw(bounds)
        advance = math.floor(font['hmtx'][name][0] * scale + .5)
        if bounds.bounds is None:
            result[codepoint] = {'advance': advance, 'x': 0, 'y': 0, 'rows': []}
            continue
        xmin, ymin, xmax, ymax = bounds.bounds
        left, right = math.floor(xmin * scale), math.ceil(xmax * scale)
        top, bottom = math.floor(-ymax * scale), math.ceil(-ymin * scale)
        rows = []
        for y in range(top, bottom):
            bits = 0
            for x in range(left, right):
                pen = PointInsidePen(glyph_set, ((x + .5) / scale, -(y + .5) / scale))
                glyph.draw(pen)
                if pen.getResult():
                    bits |= 1 << (x - left)
            rows.append(bits)
        # Remove empty boundary rows introduced by tiny rounding differences in
        # the original font's integer outline units.
        while rows and rows[0] == 0:
            rows.pop(0)
            top += 1
        while rows and rows[-1] == 0:
            rows.pop()
        result[codepoint] = {'advance': advance, 'x': left, 'y': top, 'rows': rows}
    return result


def source_text(fonts: dict) -> str:
    lines = [
        '// Generated by scripts/generate-bitmap-font.py. Do not hand-edit glyph data.',
        '// MS Sans Serif / MS Sans Serif Bold by lou (FontStruct), CC BY-SA 3.0.',
        '// This 11px bitmap adaptation is also CC BY-SA 3.0; see docs/fonts/ATTRIBUTION.md.',
        '// Pixel-centre outline tests; no browser hinting or fillText is involved.',
        'export interface BitmapGlyph { advance: number; x: number; y: number; rows: readonly number[] }',
        'export const BITMAP_FONTS: Record<\'ui\' | \'bold\', Readonly<Record<number, BitmapGlyph>>> = {',
    ]
    for family, glyphs in fonts.items():
        lines.append(f'  {family}: {{')
        for codepoint, glyph in glyphs.items():
            rows = ', '.join(map(str, glyph['rows']))
            lines.append(f"    {codepoint}: {{ advance: {glyph['advance']}, x: {glyph['x']}, y: {glyph['y']}, rows: [{rows}] }},")
        lines.append('  },')
    lines.extend([
        '};', '',
        '/** The bold source omits punctuation; use its regular companion for those glyphs. */',
        "export function bitmapGlyph(char: string, font: string): BitmapGlyph | undefined {",
        "  if (font !== 'ui' && font !== 'bold') return undefined;",
        '  const code = char.codePointAt(0);',
        '  if (code === undefined) return undefined;',
        '  return BITMAP_FONTS[font][code] ?? BITMAP_FONTS.ui[code];',
        '}', '',
    ])
    return '\n'.join(lines)


def preview(fonts: dict, path: Path) -> None:
    from PIL import Image, ImageDraw
    image = Image.new('RGB', (430, 172), '#008080')
    draw = ImageDraw.Draw(image)
    draw.rectangle((8, 8, 421, 163), fill='#c0c0c0', outline='white')
    lines = [
        ('bold', 'MS Sans Serif - deterministic 11px', 14, '#000080', 'white'),
        ('ui', 'My Computer   Training Data   Minesweeper', 36, '#c0c0c0', 'black'),
        ('ui', 'Probability of doom: 99.9%   OK   Cancel', 56, '#c0c0c0', 'black'),
        ('ui', 'ABCDEFGHIJKLMNOPQRSTUVWXYZ 0123456789', 76, '#c0c0c0', 'black'),
        ('ui', 'abcdefghijklmnopqrstuvwxyz !?.,:;()[]', 96, '#c0c0c0', 'black'),
        ('bold', 'Minesweeper  P(doom) Properties  Start', 116, '#c0c0c0', 'black'),
        ('bold', 'Hamburgefontsiv  il1I MW  gypq  99.9%', 136, '#c0c0c0', 'black'),
    ]
    for family, text, top, background, color in lines:
        draw.rectangle((12, top - 2, 417, top + 14), fill=background)
        x = 16
        for char in text:
            glyph = fonts[family].get(ord(char)) or fonts['ui'].get(ord(char))
            if glyph is None:
                x += 6
                continue
            for row, bits in enumerate(glyph['rows']):
                for bit in range(bits.bit_length()):
                    if bits & (1 << bit):
                        draw.point((x + glyph['x'] + bit, top + 9 + glyph['y'] + row), fill=color)
            x += glyph['advance']
    path.parent.mkdir(parents=True, exist_ok=True)
    image.resize((1290, 516), Image.Resampling.NEAREST).save(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--preview', type=Path)
    args = parser.parse_args()
    fonts = {family: generate(path) for family, path in SOURCES.items()}
    output = source_text(fonts)
    if args.check:
        if DESTINATION.read_text(encoding='utf-8') != output:
            raise SystemExit('Generated bitmap font is out of date.')
        print('Bitmap glyph data matches source outlines.')
    else:
        DESTINATION.write_text(output, encoding='utf-8', newline='\n')
        print(f'Generated {sum(map(len, fonts.values()))} glyphs in {DESTINATION}')
    if args.preview:
        preview(fonts, args.preview)
    print(json.dumps({family: hashlib.sha256(path.read_bytes()).hexdigest() for family, path in SOURCES.items()}, indent=2))


if __name__ == '__main__':
    main()
