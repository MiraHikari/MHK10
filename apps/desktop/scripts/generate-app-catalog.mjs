// Generates the build-safe catalog snapshot from the per-application registration sidecars.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format } from 'vite-plus/fmt';
import { formatOptions } from '../../../scripts/format-policy.mjs';

const appsDir = new URL('../src/lib/apps/', import.meta.url);
const target = new URL('../src/data/app-catalog.generated.ts', import.meta.url);

function registrationFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const file = join(directory, entry.name);
    if (entry.isDirectory()) return registrationFiles(file);
    return entry.isFile() && entry.name.endsWith('.registration.ts') ? [file] : [];
  });
}

function validRegistration(value) {
  return (
    value !== null &&
    typeof value === 'object' &&
    !Array.isArray(value) &&
    typeof value.id === 'string' &&
    /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(value.id) &&
    value.kind === 'canvas' &&
    typeof value.name === 'string' &&
    value.name.trim().length > 0 &&
    typeof value.title === 'string' &&
    value.title.trim().length > 0 &&
    Number.isSafeInteger(value.w) &&
    value.w > 0 &&
    Number.isSafeInteger(value.h) &&
    value.h > 0 &&
    (value.x === undefined || Number.isSafeInteger(value.x)) &&
    (value.y === undefined || Number.isSafeInteger(value.y))
  );
}

export async function buildCatalogSnapshotSource(directory = appsDir) {
  const source = fileURLToPath(directory);
  const sidecars = registrationFiles(source).sort();
  const entries = [];
  const registered = new Map();
  for (const file of sidecars) {
    const name = relative(source, file).replaceAll('\\', '/');
    const module = await import(pathToFileURL(file).href);
    const value = module.registration;
    if (!validRegistration(value)) throw new Error(`Invalid registration sidecar: ${name}`);
    if (registered.has(value.id))
      throw new Error(
        `Duplicate application registration: ${value.id} (${registered.get(value.id)}, ${name})`,
      );
    registered.set(value.id, name);
    const candidates = readdirSync(dirname(file)).filter((name) => name.endsWith('.app.ts'));
    if (candidates.length > 1) throw new Error(`Ambiguous application entry for ${name}`);
    const implementation =
      candidates[0] ?? name.split('/').at(-1).replace('.registration.ts', '.app.ts');
    const modulePath = `./${relative(source, join(dirname(file), implementation)).replaceAll('\\', '/')}`;
    entries.push({ ...value, modulePath });
  }
  entries.sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0));
  const generated = `// Generated by scripts/generate-app-catalog.mjs from src/lib/apps/**/*.registration.ts; run npm run generate:app-catalog after edits.\nexport const CANVAS_APPS = ${JSON.stringify(entries, null, 2)} as const;\n`;
  const formatted = await format('src/data/app-catalog.generated.ts', generated, formatOptions);
  if (formatted.errors.length) throw new Error('Could not format the generated catalog snapshot');
  return formatted.code;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  writeFileSync(target, await buildCatalogSnapshotSource());
  console.log('Generated src/data/app-catalog.generated.ts');
}
