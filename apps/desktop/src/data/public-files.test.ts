import { expect, it } from 'vite-plus/test';
import {
  publicAssetPath,
  publicFileTarget,
  publicLibrary,
  publicArticles,
  readPublicArticle,
} from './public-files';
import { mediaCatalog } from './media';
it('mounts complete immutable articles and deduplicated images by stable identities', () => {
  expect(new Set(publicLibrary.files.map((file) => file.id)).size).toBe(publicLibrary.files.length);
  expect(publicLibrary.files.every((file) => file.readonly && !file.deleted)).toBe(true);
  expect(publicLibrary.files.filter((file) => file.kind === 'image')).toHaveLength(
    mediaCatalog.length,
  );
  expect(
    publicLibrary.files.filter((file) => file.kind === 'text').map((file) => file.name),
  ).toEqual(['advx-2026-hangzhou.md', 'colophon.md', 'mhk10-technical.md', 'privacy.md']);
  expect(publicFileTarget('library:article:colophon')).toEqual({
    application: 'blog',
    href: '/blog/colophon/',
  });
  for (const file of publicLibrary.files.filter((file) => file.kind === 'image'))
    expect(publicAssetPath(file.assetId!)).toMatch(/^\/(?!\/)/);
  expect(publicAssetPath('https://untrusted.invalid/image.png')).toBeUndefined();
});

it('keeps retired article identities addressable without mounting the withdrawn documents', () => {
  for (const slug of ['site-update']) {
    const id = `library:article:${slug}`;
    expect(publicFileTarget(id)).toEqual({ application: 'blog', href: '/blog/colophon/' });
    expect(publicLibrary.files.some((file) => file.id === id)).toBe(false);
  }
  expect(publicFileTarget('library:article:missing')).toBeUndefined();
});

it('loads complete selected publication text with generated byte metadata', async () => {
  for (const article of publicArticles) {
    const content = await readPublicArticle(article.slug);
    expect(content).toContain(`title: ${article.title}`);
    expect(new TextEncoder().encode(content).length).toBe(article.bytes);
    expect(
      publicLibrary.files.find((file) => file.id === `library:article:${article.slug}`)?.content,
    ).toBe('');
  }
  expect(await readPublicArticle('../private')).toBeUndefined();
  expect(await publicLibrary.readText('missing')).toBeUndefined();
});
